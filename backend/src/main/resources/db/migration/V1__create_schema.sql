-- =====================================================================
-- V1: HealthDekho current-scope schema (README section 5.2) - exactly 7 tables.
-- IDs: BIGINT identity | Money: NUMERIC(19,2) | Dates: DATE | Audit: TIMESTAMPTZ
-- Claim tables (FE-1) are intentionally NOT created.
-- =====================================================================

-- 1. customer ---------------------------------------------------------
CREATE TABLE customer (
    customer_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(150) NOT NULL,
    password_hash   VARCHAR(100) NOT NULL,
    full_name       VARCHAR(150) NOT NULL,
    date_of_birth   DATE         NOT NULL,
    phone           VARCHAR(15)  NOT NULL,
    status          VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_customer_email  UNIQUE (email),
    CONSTRAINT ck_customer_dob    CHECK (date_of_birth <= CURRENT_DATE),
    CONSTRAINT ck_customer_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'LOCKED'))
);
CREATE INDEX idx_customer_status    ON customer (status);
CREATE INDEX idx_customer_name_ci   ON customer (lower(full_name));   -- FR-5 search by name
CREATE INDEX idx_customer_dob       ON customer (date_of_birth);      -- FR-5 search by ID + DOB

-- 2. insurance_product (master catalog) -------------------------------
CREATE TABLE insurance_product (
    product_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code       VARCHAR(30)   NOT NULL,
    policy_name        VARCHAR(150)  NOT NULL,
    policy_type        VARCHAR(20)   NOT NULL,
    term_months        INTEGER       NOT NULL,
    premium_frequency  VARCHAR(20)   NOT NULL,
    premium_amount     NUMERIC(19,2) NOT NULL,
    sum_insured        NUMERIC(19,2) NOT NULL,
    min_entry_age      INTEGER       NOT NULL,
    max_entry_age      INTEGER       NOT NULL,
    active             BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_product_code        UNIQUE (product_code),
    CONSTRAINT ck_product_type        CHECK (policy_type IN ('TERM', 'HEALTH', 'SAVINGS', 'LIFE')),
    CONSTRAINT ck_product_frequency   CHECK (premium_frequency IN ('MONTHLY', 'QUARTERLY', 'HALF_YEARLY', 'YEARLY')),
    CONSTRAINT ck_product_premium     CHECK (premium_amount > 0),
    CONSTRAINT ck_product_sum_insured CHECK (sum_insured > 0),
    CONSTRAINT ck_product_term        CHECK (term_months > 0),
    CONSTRAINT ck_product_ages        CHECK (min_entry_age >= 0 AND min_entry_age <= max_entry_age),
    -- term must split into whole installments (e.g. QUARTERLY needs a multiple of 3 months)
    CONSTRAINT ck_product_term_fits_frequency CHECK (
        term_months % CASE premium_frequency
                          WHEN 'MONTHLY'     THEN 1
                          WHEN 'QUARTERLY'   THEN 3
                          WHEN 'HALF_YEARLY' THEN 6
                          ELSE 12
                      END = 0)
);
CREATE INDEX idx_product_active ON insurance_product (active);

-- 3. customer_policy --------------------------------------------------
CREATE TABLE customer_policy (
    policy_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_number          VARCHAR(30)   NOT NULL,
    customer_id            BIGINT        NOT NULL REFERENCES customer (customer_id),
    product_id             BIGINT        NOT NULL REFERENCES insurance_product (product_id),
    start_date             DATE          NOT NULL,
    maturity_date          DATE          NOT NULL,
    premium_frequency      VARCHAR(20)   NOT NULL,
    premium_amount         NUMERIC(19,2) NOT NULL,
    sum_insured            NUMERIC(19,2) NOT NULL,
    total_premium_payable  NUMERIC(19,2) NOT NULL,
    status                 VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE',
    created_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_policy_number            UNIQUE (policy_number),
    CONSTRAINT uq_policy_customer_product  UNIQUE (customer_id, product_id),   -- duplicate-registration rule
    CONSTRAINT ck_policy_dates             CHECK (maturity_date > start_date),
    CONSTRAINT ck_policy_frequency         CHECK (premium_frequency IN ('MONTHLY', 'QUARTERLY', 'HALF_YEARLY', 'YEARLY')),
    CONSTRAINT ck_policy_premium           CHECK (premium_amount > 0),
    CONSTRAINT ck_policy_sum_insured       CHECK (sum_insured > 0),
    CONSTRAINT ck_policy_total             CHECK (total_premium_payable > 0),
    CONSTRAINT ck_policy_status            CHECK (status IN ('ACTIVE', 'FULLY_PAID', 'LAPSED', 'MATURED', 'CANCELLED'))
);
CREATE INDEX idx_policy_customer ON customer_policy (customer_id);
CREATE INDEX idx_policy_product  ON customer_policy (product_id);
CREATE INDEX idx_policy_status   ON customer_policy (status);

-- 4. premium_installment ----------------------------------------------
CREATE TABLE premium_installment (
    installment_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id              BIGINT        NOT NULL REFERENCES customer_policy (policy_id),
    installment_number     INTEGER       NOT NULL,
    due_date               DATE          NOT NULL,
    grace_period_end_date  DATE          NOT NULL,
    scheduled_amount       NUMERIC(19,2) NOT NULL,
    paid_amount            NUMERIC(19,2) NOT NULL DEFAULT 0,
    payment_status         VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    created_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_installment_policy_number UNIQUE (policy_id, installment_number),
    CONSTRAINT ck_installment_number        CHECK (installment_number > 0),
    CONSTRAINT ck_installment_grace         CHECK (grace_period_end_date >= due_date),
    CONSTRAINT ck_installment_scheduled     CHECK (scheduled_amount > 0),
    -- paid between 0 and scheduled + max 10% late penalty
    CONSTRAINT ck_installment_paid          CHECK (paid_amount >= 0 AND paid_amount <= ROUND(scheduled_amount * 1.10, 2)),
    CONSTRAINT ck_installment_status        CHECK (payment_status IN ('PAID', 'PENDING', 'PARTIALLY_PAID', 'OVERDUE'))
);
CREATE INDEX idx_installment_due_date ON premium_installment (due_date);
CREATE INDEX idx_installment_status   ON premium_installment (payment_status);

-- 5. premium_payment (immutable history) ------------------------------
CREATE TABLE premium_payment (
    payment_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installment_id         BIGINT        NOT NULL REFERENCES premium_installment (installment_id),
    transaction_reference  VARCHAR(40)   NOT NULL,
    payment_date           DATE          NOT NULL,
    amount_paid            NUMERIC(19,2) NOT NULL,
    penalty_amount         NUMERIC(19,2) NOT NULL DEFAULT 0,
    payment_method         VARCHAR(20)   NOT NULL,
    created_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_payment_txn_ref  UNIQUE (transaction_reference),
    CONSTRAINT ck_payment_amount   CHECK (amount_paid > 0),
    CONSTRAINT ck_payment_penalty  CHECK (penalty_amount >= 0),
    CONSTRAINT ck_payment_method   CHECK (payment_method IN ('UPI', 'NET_BANKING', 'CARD', 'CASH', 'CHEQUE'))
);
CREATE INDEX idx_payment_installment ON premium_payment (installment_id);
CREATE INDEX idx_payment_date        ON premium_payment (payment_date);

-- Payments are history: block UPDATE/DELETE at the database level.
CREATE FUNCTION prevent_payment_change() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'premium_payment rows are immutable (payment_id=%)', OLD.payment_id;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_premium_payment_immutable
    BEFORE UPDATE OR DELETE ON premium_payment
    FOR EACH ROW EXECUTE FUNCTION prevent_payment_change();

-- 6. ai_recommendation_request ----------------------------------------
CREATE TABLE ai_recommendation_request (
    recommendation_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id               BIGINT        NOT NULL REFERENCES customer (customer_id),
    insurance_goals           VARCHAR(1000),
    preferred_term            VARCHAR(50),
    preferred_policy_type     VARCHAR(20),
    calculated_age            INTEGER       NOT NULL,
    model_name                VARCHAR(100)  NOT NULL,
    model_version             VARCHAR(100),
    prompt_version            VARCHAR(20)   NOT NULL,
    requested_at              TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_ai_request_age CHECK (calculated_age >= 0)
);
CREATE INDEX idx_ai_request_customer     ON ai_recommendation_request (customer_id);
CREATE INDEX idx_ai_request_requested_at ON ai_recommendation_request (requested_at);

-- 7. ai_recommendation_item -------------------------------------------
-- "Product must be active at generation time" is checked in the service layer (Step 9).
CREATE TABLE ai_recommendation_item (
    recommendation_item_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommendation_request_id  BIGINT        NOT NULL REFERENCES ai_recommendation_request (recommendation_request_id),
    product_id                 BIGINT        NOT NULL REFERENCES insurance_product (product_id),
    rank_order                 INTEGER       NOT NULL,
    recommendation_reason      VARCHAR(1000) NOT NULL,
    suitability                VARCHAR(10)   NOT NULL,
    selected_for_registration  BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_ai_item_request_product UNIQUE (recommendation_request_id, product_id),
    CONSTRAINT uq_ai_item_request_rank    UNIQUE (recommendation_request_id, rank_order),
    CONSTRAINT ck_ai_item_rank            CHECK (rank_order > 0),
    CONSTRAINT ck_ai_item_suitability     CHECK (suitability IN ('HIGH', 'MEDIUM', 'LOW'))
);
CREATE INDEX idx_ai_item_product ON ai_recommendation_item (product_id);
