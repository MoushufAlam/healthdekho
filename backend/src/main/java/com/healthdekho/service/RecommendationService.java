package com.healthdekho.service;

import com.healthdekho.ai.AiRecommendationInput;
import com.healthdekho.ai.AiSuggestion;
import com.healthdekho.ai.AiUnavailableException;
import com.healthdekho.ai.RecommendationAiClient;
import com.healthdekho.config.AppProperties;
import com.healthdekho.dto.product.ProductResponse;
import com.healthdekho.dto.recommendation.RecommendationRequest;
import com.healthdekho.dto.recommendation.RecommendationResponse;
import com.healthdekho.dto.recommendation.RecommendationSource;
import com.healthdekho.dto.recommendation.RecommendedProductResponse;
import com.healthdekho.entity.AiRecommendationItem;
import com.healthdekho.entity.AiRecommendationRequest;
import com.healthdekho.entity.Customer;
import com.healthdekho.entity.enums.Suitability;
import com.healthdekho.exception.BusinessRuleException;
import com.healthdekho.repository.AiRecommendationItemRepository;
import com.healthdekho.repository.AiRecommendationRequestRepository;
import com.healthdekho.repository.CustomerRepository;
import com.healthdekho.repository.InsuranceProductRepository;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import org.springframework.transaction.support.TransactionTemplate;

import java.time.Clock;
import java.time.LocalDate;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.concurrent.TimeoutException;
import java.util.function.Function;
import java.util.stream.Collectors;
import java.util.stream.IntStream;

@Slf4j
@Service
@RequiredArgsConstructor
public class RecommendationService {

    private static final int MAX_REASON_LENGTH = 1000;

    private final CustomerService customerService;
    private final ProductService productService;
    private final RecommendationAiClient aiClient;
    private final RuleBasedRecommender ruleBasedRecommender;
    private final AiRecommendationRequestRepository requestRepository;
    private final AiRecommendationItemRepository itemRepository;
    private final CustomerRepository customerRepository;
    private final InsuranceProductRepository productRepository;
    private final TransactionTemplate transactionTemplate;
    private final AppProperties properties;
    private final Clock clock;

    // Not @Transactional on purpose: the AI call can take seconds and must not hold a DB connection.
    // Only the final save runs in a (short) transaction.
    public RecommendationResponse recommend(Long customerId, RecommendationRequest request) {
        if (!request.hasAnyInput()) {
            throw new BusinessRuleException(
                    "Provide at least one of: date of birth, insurance goals, preferred term or policy type");
        }
        LocalDate today = LocalDate.now(clock);
        Customer customer = customerService.getCustomer(customerId);
        LocalDate dateOfBirth = request.dateOfBirth() != null ? request.dateOfBirth() : customer.getDateOfBirth();
        if (dateOfBirth.isAfter(today)) {
            throw new BusinessRuleException("Date of birth cannot be in the future");
        }
        int age = AgeCalculator.ageOn(dateOfBirth, today);
        int limit = properties.ai().maxRecommendations();

        // Java decides what is allowed (active, not owned, age fits); the AI only ranks and explains
        List<ProductResponse> candidates = productService.availableProductsFor(customerId).stream()
                .filter(product -> age >= product.getMinEntryAge() && age <= product.getMaxEntryAge())
                .map(ProductResponse::from)
                .toList();

        Outcome outcome = candidates.isEmpty()
                ? new Outcome(RecommendationSource.FALLBACK, RuleBasedRecommender.MODEL_NAME, "1", List.of(),
                "No products are available for your age (%d) that you don't already hold".formatted(age))
                : generate(request, age, candidates, limit);

        return transactionTemplate.execute(status -> persist(customerId, request, age, outcome));
    }

    private Outcome generate(RecommendationRequest request, int age, List<ProductResponse> candidates, int limit) {
        try {
            List<AiSuggestion> suggestions = aiClient.suggest(new AiRecommendationInput(age,
                    request.insuranceGoals(), request.preferredTerm(), request.preferredPolicyType(),
                    candidates, limit));
            List<Pick> picks = validated(suggestions, candidates, limit);
            if (!picks.isEmpty()) {
                return new Outcome(RecommendationSource.AI, aiClient.modelName(), aiClient.modelVersion(), picks,
                        "Personalised recommendations generated by AI");
            }
            log.warn("AI answered but suggested no valid products; using rule-based fallback");
            return fallback(request, candidates, limit, "the AI suggested no valid products");
        } catch (RuntimeException ex) {
            log.warn("AI recommendation failed: {}", ex.getMessage());
            return fallback(request, candidates, limit, describe(ex));
        }
    }

    // Drop anything the model made up: unknown codes, duplicates, owned or ineligible products.
    private List<Pick> validated(List<AiSuggestion> suggestions, List<ProductResponse> candidates, int limit) {
        Map<String, ProductResponse> byCode = candidates.stream()
                .collect(Collectors.toMap(ProductResponse::productCode, Function.identity()));
        Map<String, AiSuggestion> unique = new LinkedHashMap<>();
        suggestions.stream()
                .filter(s -> s != null && s.productCode() != null)
                .sorted(Comparator.comparing(AiSuggestion::rank, Comparator.nullsLast(Comparator.naturalOrder())))
                .forEach(s -> {
                    String code = s.productCode().trim().toUpperCase(Locale.ROOT);
                    if (byCode.containsKey(code)) {
                        unique.putIfAbsent(code, s);
                    }
                });
        return unique.entrySet().stream()
                .limit(limit)
                .map(entry -> new Pick(byCode.get(entry.getKey()), cleanReason(entry.getValue().reason()),
                        parseSuitability(entry.getValue().suitability())))
                .toList();
    }

    private Outcome fallback(RecommendationRequest request, List<ProductResponse> candidates, int limit,
                             String why) {
        List<Pick> picks = ruleBasedRecommender
                .rank(candidates, request.insuranceGoals(), request.preferredTerm(), request.preferredPolicyType(),
                        limit)
                .stream()
                .map(ranked -> new Pick(ranked.product(), ranked.reason(), ranked.suitability()))
                .toList();
        return new Outcome(RecommendationSource.FALLBACK, RuleBasedRecommender.MODEL_NAME, "1", picks,
                "AI recommendations are unavailable right now (%s). Showing rule-based recommendations instead."
                        .formatted(why));
    }

    private RecommendationResponse persist(Long customerId, RecommendationRequest request, int age, Outcome outcome) {
        AiRecommendationRequest saved = new AiRecommendationRequest();
        saved.setCustomer(customerRepository.getReferenceById(customerId));
        saved.setInsuranceGoals(trimToNull(request.insuranceGoals()));
        saved.setPreferredTerm(trimToNull(request.preferredTerm()));
        saved.setPreferredPolicyType(request.preferredPolicyType());
        saved.setCalculatedAge(age);
        saved.setModelName(outcome.modelName());
        saved.setModelVersion(outcome.modelVersion());
        saved.setPromptVersion(properties.ai().promptVersion());
        requestRepository.save(saved);

        List<AiRecommendationItem> items = IntStream.range(0, outcome.picks().size())
                .mapToObj(index -> {
                    Pick pick = outcome.picks().get(index);
                    AiRecommendationItem item = new AiRecommendationItem();
                    item.setRequest(saved);
                    item.setProduct(productRepository.getReferenceById(pick.product().productId()));
                    item.setRankOrder(index + 1);
                    item.setRecommendationReason(pick.reason());
                    item.setSuitability(pick.suitability());
                    return item;
                })
                .toList();
        itemRepository.saveAll(items);

        List<RecommendedProductResponse> recommendations = IntStream.range(0, items.size())
                .mapToObj(index -> toResponse(items.get(index), outcome.picks().get(index).product()))
                .toList();
        return new RecommendationResponse(saved.getId(), age, outcome.source(), outcome.modelName(),
                outcome.message(), recommendations);
    }

    private static RecommendedProductResponse toResponse(AiRecommendationItem item, ProductResponse product) {
        return new RecommendedProductResponse(item.getId(), item.getRankOrder(), product.productId(),
                product.productCode(), product.policyName(), product.policyType(), product.termMonths(),
                product.sumInsured(), product.premiumFrequency(), product.premiumAmount(),
                item.getRecommendationReason(), item.getSuitability());
    }

    private static String describe(RuntimeException ex) {
        if (ex instanceof AiUnavailableException unavailable && unavailable.getCause() instanceof TimeoutException) {
            return "the AI took too long to answer";
        }
        if (ex instanceof AiUnavailableException unavailable) {
            return unavailable.getMessage();
        }
        return "unexpected AI error";
    }

    private static String cleanReason(String reason) {
        if (reason == null || reason.isBlank()) {
            return "Recommended for your profile.";
        }
        String trimmed = reason.trim();
        return trimmed.length() <= MAX_REASON_LENGTH ? trimmed : trimmed.substring(0, MAX_REASON_LENGTH);
    }

    private static Suitability parseSuitability(String value) {
        if (value == null) {
            return Suitability.MEDIUM;
        }
        try {
            return Suitability.valueOf(value.trim().toUpperCase(Locale.ROOT));
        } catch (IllegalArgumentException ex) {
            return Suitability.MEDIUM;
        }
    }

    private static String trimToNull(String value) {
        return value == null || value.isBlank() ? null : value.trim();
    }

    private record Pick(ProductResponse product, String reason, Suitability suitability) {
    }

    private record Outcome(RecommendationSource source, String modelName, String modelVersion, List<Pick> picks,
                           String message) {
    }
}
